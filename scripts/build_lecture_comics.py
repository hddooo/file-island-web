def bold_terms(text, seen, vocab=None):
    """장면 안에서 강의 핵심어를 처음 나올 때 한 번만 굵게(긴 말부터 맞춘다). vocab을 주지 않으면 고려 핵심어."""
    terms = sorted((t for t in (G_TERMS if vocab is None else vocab) if t not in seen), key=len, reverse=True)
    if not terms:
        return e(text)
    rx = re.compile('|'.join(re.escape(t) for t in terms))
    out, pos = [], 0
    for m in rx.finditer(text):
        if m.group(0) in seen:
            continue
        seen.add(m.group(0))
        out.append(e(text[pos:m.start()]) + '<strong>' + e(m.group(0)) + '</strong>')
        pos = m.end()
    return ''.join(out) + e(text[pos:])


