def goryeo_scene(sc, n):
    a = art_of(sc)
    idattr = ' id="%s"' % e(sc['id']) if sc.get('id') else ''
    kings = ' data-kings="%d-%d"' % sc['kings'] if sc.get('kings') else ''
    year = ' data-year="%d"' % sc['year'] if sc.get('year') else ''
    reign = ('<p class="g-reign"><b class="king">%s</b><span class="years">%s</span></p>' % (e(sc['reign'][0]), e(sc['reign'][1]))) if sc.get('reign') else ''
    head = ('<div class="caption"><div class="meta"><span data-scene-count data-format="n">%02d</span> · %s %s</div><h2>%s</h2>%s<p class="g-when">%s</p></div>'
            % (n, e(sc['label']), tier_badge(sc['tier']), e(sc['title']), reign, e(sc['when'])))
    load = 'eager' if n <= 2 else 'lazy'
    # 그림 칸은 실제 그림의 가로:세로(--g-ar)만큼 미리 자리를 잡는다 — 늦게 불러오는(lazy) 그림이 오기 전에도 높이가 0이 되지 않아, 바로 가기 뒤 위치가 밀리지 않는다
    art = '<div class="artwork full" style="--g-ar:%d / %d"><img src="%s" width="%d" height="%d" alt="%s" decoding="async" loading="%s"></div>' % (a[1], a[2], a[0], a[1], a[2], e(sc['alt']), load)
    note = '<p class="g-art-note">%s</p>' % e(sc['art_note']) if sc.get('art_note') else ''
    talk = '<p class="g-talk-cap">학습용 요약 대화 · 실제 발언을 그대로 옮긴 것이 아니에요.</p><div class="dialogue g-talk">%s</div>' % g_dialogue(sc)
    seen = set()
    steps = '<ol class="g-steps" aria-label="장면 흐름">%s</ol>' % ''.join(
        '<li><b class="st %s">%s</b><span>%s</span></li>' % (k, e(lbl), bold_terms(t, seen)) for lbl, k, t in sc['steps'])
    return '<section class="scene"%s data-lecture="%s"%s%s>%s%s%s%s%s%s%s%s</section>' % (
        idattr, e(' '.join(sc['mods'])), kings, year, legacy_spans(sc), head, art, note, talk, steps, g_key(sc['key']), g_mores(sc))


def g_bridge(sc):
    if not sc.get('next'):
        return ''
    text, leap = sc['next']
    cls = 'bridge g-part' if sc.get('part') else 'bridge'
    chip = '<span class="leap">중간 왕 생략</span>' if leap else ''
    return '<div class="%s" aria-label="다음 이야기"%s><span class="bridge-dots" aria-hidden="true">…</span><span class="bridge-text">%s</span>%s</div>' % (
        cls, ' data-leap="1"' if leap else '', e(text), chip)


