J_MEMORY = []


def build_joseon():
    """세 조선 웹툰(전기 · 후기 · 통합)을 다섯 흐름으로 엮는다. 장면 순서·id·그림은 그대로이고,
    흐름이 시작하는 곳에 흐름 머리, 덩어리의 마지막 장면 뒤에 ‘이 부분에서 외울 것’ 카드를 넣는다(장면 → 카드 → 다음 장면으로 잇는 줄)."""
    meta = []
    keys, starts, ends, flow = j_flow_plan()
    flows = flow['list']
    flow_of = lambda key: [f for f in flows if keys.index(f['start']) <= keys.index(key)][-1]

    def card(file, key, n):
        old_starts=[k['go'] for group in flows for k in group['chunks']]
        old_ends=[keys[keys.index(x)-1] for x in old_starts[1:]]+[keys[-1]]
        if key not in ends:
            return '<span class="legacy-anchor" id="mem-%s" aria-hidden="true"></span>' % e(key) if key in old_ends else ''
        if file == 'joseon-all-comic.html' and key == 'E%02d' % len(EARLY):
            return '<span class="legacy-anchor" id="mem-%s" aria-hidden="true"></span>' % e(key)
        selected = ends[key]
        if file == 'joseon-late-comic.html' and key == 'L01':
            selected = [k for k in selected if k['go'].startswith('L')]
        J_MEMORY.append(dict(file=file, after=key, scene=n, chunks=[k['t'] for k in selected]))
        return j_memory(key, selected)

    # 전기(①–③의 앞부분)
    body = ''
    for i, sc in enumerate(EARLY, 1):
        key = 'E%02d' % i
        body += (j_flow_head(starts[key]) if key in starts else '') + joseon_scene(sc, i, 'joseon-early') + card('joseon-comic.html', key, i) + j_bridge(sc) + '\n'
        meta.append(j_meta(sc, 'joseon-comic.html', i))
    early_flows = [f for f in flows if f['start'].startswith('E')]
    header = ('<header><small>시대 웹툰 · 조선 전기와 양난</small><h1>나라의 틀을 세우고,<br>사화와 전쟁을 지나</h1><p>1대 태조의 건국부터 16대 인조의 병자호란까지, 왕과 사건을 순서대로 따라가요.</p>' + J_GUIDE +
              '<span class="intro-tag">배지: 먼저 기억 · 1급 보충 · 흐름 보충 · 선택 심화</span></header>\n' + j_nav(early_flows, '흐름 바로 가기'))
    end = '<div class="end"><strong>조선 전기와 양난, 한 줄로</strong>' + EARLY_END + '<a href="../index.html#chapter/joseon-early/quiz" target="_top">다 읽었다면 퀴즈로 확인하기 →</a></div>\n'
    write('joseon-comic.html', joseon_doc('joseon-comic.html', header, body, end))
    # 후기(③의 끝 효종 → ④ → ⑤)
    moved = '<div class="chapter-line" id="moved-early">선조·광해군·인조 이야기는 <a href="joseon-comic.html#bungdang-origin">1부 ‘조선 전기와 양난’</a>으로 옮겼어요. 2부는 효종부터 시작해요.<span class="legacy-anchor" id="bungdang-origin" aria-hidden="true"></span><span class="legacy-anchor" id="gwanghaegun" aria-hidden="true"></span><span class="legacy-anchor" id="injo" aria-hidden="true"></span></div>\n'
    body = ''
    for i, sc in enumerate(LATE, 1):
        key = 'L%02d' % i
        head = j_flow_head(starts[key]) if key in starts else (j_flow_head(flow_of(key), cont=True) if i == 1 else '')
        body += head + joseon_scene(sc, i, 'joseon-late') + card('joseon-late-comic.html', key, i) + j_bridge(sc) + '\n'
        meta.append(j_meta(sc, 'joseon-late-comic.html', i))
    late_flows = [flow_of('L01')] + [f for f in flows if f['start'].startswith('L')]
    header = ('<header><small>한국사 한눈에 · 시대 웹툰</small><h1>조선 후기</h1><p>17대 효종의 북벌부터 예송·환국, 영조·정조의 개혁, 세도정치와 달라진 사회까지</p>' + J_GUIDE + '</header>\n' + j_nav(late_flows, '흐름 바로 가기'))
    end = '<div class="end"><strong>이 시대 한 줄 흐름</strong>' + LATE_END + '<a href="../index.html#chapter/joseon-late/quiz" target="_top">다 읽었다면 퀴즈로 확인하기 →</a></div>\n'
    write('joseon-late-comic.html', joseon_doc('joseon-late-comic.html', header, moved + body, end))
    # 통합: 다섯 흐름(번호는 이어서). 예전 1부·2부 앵커(#early-part · #late-part)는 같은 자리의 빈 앵커로 남긴다
    early_ids = {x for sc in EARLY for x in ([sc['id']] if sc.get('id') else []) + sc.get('legacy', [])}
    body = '<span class="legacy-anchor" id="early-part" aria-hidden="true"></span>'
    for i, sc in enumerate(EARLY, 1):
        key = 'E%02d' % i
        body += (j_flow_head(starts[key]) if key in starts else '') + joseon_scene(sc, i, 'joseon-early', ' data-part="early"') + card('joseon-all-comic.html', key, i) + j_bridge(sc) + '\n'
    body += ('<div class="bridge" aria-label="다음 이야기"><span class="bridge-dots" aria-hidden="true">…</span><span class="bridge-text">1649년 인조의 아들 17대 효종이 즉위했다.</span></div>'
             '<span class="legacy-anchor" id="late-part" aria-hidden="true"></span>\n')
    for j, sc in enumerate(LATE, len(EARLY) + 1):
        key = 'L%02d' % (j - len(EARLY))
        body += (j_flow_head(starts[key]) if key in starts else '') + joseon_scene(sc, j, 'joseon-late', ' data-part="late"', skip_legacy=early_ids, late_art=True) + card('joseon-all-comic.html', key, j) + j_bridge(sc) + '\n'
    header = ('<header><small>시대 웹툰 · 조선시대</small><h1>나라의 틀을 세우고,<br>전쟁과 붕당을 지나</h1><p>건국과 제도 정비에서 세도정치까지, 다섯 흐름으로 이어 읽어요.</p>' + J_GUIDE +
              '<span class="intro-tag">장면 수 <span data-scene-total>%d</span>컷 · 배지: 먼저 기억 · 1급 보충 · 흐름 보충 · 선택 심화</span></header>' % (len(EARLY) + len(LATE)) + j_nav(flows, '다섯 흐름 바로 가기'))
    end = '<div class="end"><strong>조선시대, 한 줄로</strong>' + EARLY_END + LATE_END + '<a href="../index.html#chapter/joseon/quiz" target="_top">다 읽었다면 퀴즈로 확인하기 →</a></div>\n'
    write('joseon-all-comic.html', joseon_doc('joseon-all-comic.html', header, body, end))
    for k, sc in enumerate(EARLY + LATE, 1):
        meta.append(j_meta(sc, 'joseon-all-comic.html', k))
    return meta


