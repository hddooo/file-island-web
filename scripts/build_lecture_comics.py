def g_flow_plan():
    """장면 키(S01…S20, 고려 웹툰 순서) → 흐름 시작·덩어리 끝 카드. 장면 순서는 바꾸지 않는다."""
    keys = ['S%02d' % i for i in range(1, len(GORYEO) + 1)]
    flow = g_load_flow()
    starts = {f['start']: f for f in flow['list']}
    chunks = [k for f in flow['list'] for k in f['chunks']]
    idx = [keys.index(k['go']) for k in chunks]
    if idx != sorted(idx) or len(set(idx)) != len(idx) or any(f['start'] != f['chunks'][0]['go'] for f in flow['list']) or keys[0] != flow['list'][0]['start']:
        raise SystemExit('고려 흐름·덩어리 시작 장면 순서가 웹툰 순서와 달라요.')
    ends = {}
    for n, group in enumerate(flow['list']):
        last=keys[keys.index(flow['list'][n+1]['start'])-1] if n+1<len(flow['list']) else keys[-1]
        ends[last]=group['chunks']
    return keys, starts, ends, flow


