'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const root={};for(const id of ['cbt-explanation-data','cbt-explanation80-data'])vm.runInNewContext(fs.readFileSync('media/'+id+'.js','utf8'),{window:root});
const questions={...root.HANQ_CBT_EXPLANATIONS.items,...root.HANQ_CBT_EXPLANATIONS_80.items};
const partitions=['70-73','74-76','77-80'];
const groups={},out={};
for(const group of partitions){
 const path='docs/cbt-explanations/round-'+group+'-study-memos.json';
 if(process.argv.includes('--partial')&&!fs.existsSync(path))continue;
 const json=JSON.parse(fs.readFileSync(path,'utf8'));
 const records=json.items||json;
 assert(Object.keys(records).length>0,group);
 for(const [optionId,record] of Object.entries(records)){
  const parsed=/^(exam-(\d+)-(\d+))-option-([1-5])$/.exec(optionId);
  assert(parsed,optionId);
  const [,id,round,no,idx]=parsed,[min,max]=group.split('-').map(Number);
  assert(+round>=min&&+round<=max,optionId);
  const entry=questions[id],source=record.source;
  assert(entry&&(!record.questionId||record.questionId===id)&&(!record.version||record.version===entry.v),optionId);
  assert(source&&(!source.round||+source.round===+round)&&+source.question===+no&&+source.option===+idx,optionId);
  const item=entry.options[Number(idx)-1];
  const raw=item?.review?.find(x=>typeof x==='string'&&x.trim());
  assert(item&&item.id===optionId&&raw===source.original,optionId+' original changed');
  const clean=s=>typeof s==='string'?s.trim():'';
  const clue=clean(record.clue),subject=clean(record.subject);
  assert(clue&&subject&&Array.isArray(record.associations),optionId);
  const compact=s=>s.normalize('NFKC').replace(/[\s·ㆍ・.,·()[\]{}]/g,'');
  const clueKey=compact(clue),subjectKey=compact(subject),base=compact(clue+' · '+subject),seen=new Set();
  const memo=[...(clueKey===subjectKey?[clue]:[clue,subject])];
  assert(record.associations.length>0&&record.associations.length<=3,optionId);
  for(const term of record.associations){
   const value=clean(term),key=compact(value);
   assert(value&&key&&value.length<80,optionId+' invalid term');
   if(seen.has(key)||base.includes(key))continue;
   seen.add(key);memo.push(value);
  }
  if(seen.size===0)continue;
  assert(!out[optionId],optionId+' duplicate');
  const note=(clueKey===subjectKey?clue:clue+' · '+subject)+' · '+memo.slice(clueKey===subjectKey?1:2).join(', ');
  out[optionId]=[entry.v,raw,note,seen.size];
  groups[round]=(groups[round]||0)+1;
 }
}
const generated='/* Generated by scripts/build-cbt-round-study-memos.cjs; audited source rows under docs/cbt-explanations. */\nwindow.HANQ_CBT_ROUND_STUDY_MEMOS = {\n'+Object.entries(out).sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>' '+JSON.stringify(k)+':'+JSON.stringify(v)).join(',\n')+'\n};\n';
const target='media/cbt-round-study-memos-data.js';
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8'),generated,'stale generated study memos');else if(!process.argv.includes('--dry-run'))fs.writeFileSync(target,generated);
console.log(JSON.stringify({total:Object.keys(out).length,groups}));
