    var cut = blankBoundary(img, !!box);
    if (cut < h) show(img, cut, box);
    var key = item.exam + '-' + String(item.number).padStart(2, '0');
    var bounds = reviewed[key], src = img.currentSrc || img.src;
    if (!bounds || w !== bounds[0] || h !== bounds[1] || cut <= bounds[2] || !root.crypto?.subtle) return;
